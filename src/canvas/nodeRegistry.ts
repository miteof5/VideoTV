import { NODE_TYPE } from "@/lib/constants";
import type { CanvasNodeData } from "@/canvas/types";

// 节点注册表 —— 整个产品扩展性的枢纽。
// 加一种新节点 = 在这里加一项（标签、配色、默认参数、参数表单、输入端口、动作）。
//
// 注意：这个文件只放「元数据」，不 import 任何节点组件。
// 组件到类型的映射在 nodeTypes.ts（装配层），否则会形成循环 import。

/**
 * 一个具名输入端口。
 *
 * 第一项同时是「默认端口」：老连线没有 targetHandle 时会落到它上面。
 * 这样加了端口之后，历史项目不会因为一条边找不到归属而报错。
 */
export interface NodeInputPort {
  key: string;
  label: string;
}

/**
 * 节点动作（方案 B：能力做成节点上的动作，而不是独立节点类型）。
 *
 * 为什么动作不写进 fields 当一个下拉框：
 * 动作是「执行一次」的意图，不是节点的持久属性。存成参数的话，
 * 下次常规运行时它还会带着这个动作，用户会莫名其妙每次都被改写一遍。
 * 动作只在这一次 Job 上生效，见 schema 里的 Job.action。
 */
export interface NodeAction {
  id: string;
  label: string;
  /** 这个动作要调用哪种能力 */
  capability: "text";
  hint?: string;
  /**
   * 送给文本模型的系统指令。
   *
   * 为什么声明在这里，而不是写死在 Provider 或引擎里：
   * 「把用户的散文改写成文生图提示词」是这个**产品**的业务语义，
   * 不是模型的能力，也不是执行引擎的职责。放在动作上，加一个新动作时
   * 连同它的指令一起写，引擎和 Provider 都不用改一行。
   *
   * 真实模型的输出质量几乎完全由这段文字决定 —— 它是这个功能真正的"实现"。
   */
  systemPrompt?: string;
}

/**
 * 卡片尺寸，按**类型**固定写死。
 *
 * 为什么尺寸要声明在数据里而不是让内容撑出来：
 * React Flow 的节点尺寸是测量出来的（渲染 → ResizeObserver → node.measured），
 * 只要尺寸会变，边的端点就会滞后一帧（视觉上「甩」一下），
 * 且 handle 的 y 坐标会移动、上游连线要重连。
 * 声明成常量后，节点挂载时测一次，之后永不重排。
 *
 * 注意「恒定」约束的是**不随状态变**（选中 / 运行中 / 有无产物都不能改尺寸），
 * 不同类型可以有不同尺寸 —— 这正是创作台要「大预览」的唯一可行出口。
 */
export interface NodeSize {
  w: number;
  h: number;
}

/**
 * 卡片主体显示什么。
 * media = 大预览区（图 / 视频）；text = 提示词正文；none = 只有头部和底栏
 */
export type NodePreviewKind = "media" | "text" | "none";

/**
 * 节点在画布上的外壳形态。
 *
 *   card —— 有边框、标题栏、底栏的卡片（文本节点）
 *   bare —— 只有产物本身：没有框、没有标题栏、没有底栏（图 / 视频 / 素材）
 *
 * 为什么这必须是声明而不是组件里的 `if (preview === "media")`：
 * 「要不要外壳」是产品形态问题，不是渲染细节。将来某个图片类节点想带一点
 * 元信息栏，改这一个字段就够；写死在组件里的话，那次改动会变成
 * 「往一个 1200 行的文件里塞第五个 if」。
 *
 * bare 形态把操作按钮挪到了节点**外面**（选中时浮出），
 * 理由见 MediaNode 的注释：卡片框本身就是「看不清」的元凶，
 * 底栏那 36px 和四周的边框一起，把本来就不大的预览区又剜掉一圈。
 */
export type NodeShell = "card" | "bare";

/**
 * 一个节点能产出什么种类的产物。
 *
 * 为什么要有这个东西，而不是让引擎去 `if (type === "image.gen")`：
 * 「上游给的是图还是文」决定了视频节点走图生视频还是文生视频。
 * 这个判断必须由节点自己声明，引擎只比较种类 —— 加一种新节点时引擎零改动。
 */
export type ProducedKind = "image" | "video" | "text";

export interface NodeDefinition {
  type: string;
  label: string;
  hint: string;
  badge: string;
  size: NodeSize;
  /**
   * 尺寸是否由**产物自己的像素尺寸**决定（而不是上面那个 size 常量）。
   *
   * 声明之后 size 退化成「占位尺寸」：还没产物时用它，有了产物就按
   * 产物比例等比缩放（长边上限见 canvas/nodeSize.ts）。
   *
   * 为什么是 boolean 而不是「缩放策略对象」：目前所有产物节点用的是
   * 同一套策略（长边封顶、小图不放大）。真出现第二种策略时再把它换成
   * 一个函数字段 —— 现在写成对象只是给将来的自己多一层要读的东西。
   */
  sizeFromAsset?: true;
  /** 外壳形态。不写 = card（有边框和标题栏的卡片） */
  shell?: NodeShell;
  preview: NodePreviewKind;
  defaultData: () => CanvasNodeData;
  /**
   * 这个节点接受哪些**种类**的输入（端口层的判据）。
   *
   * 必填，不给默认值。原因很实际：漏声明时如果默认「接受一切」，
   * 症状是「悄悄又放行了一个本不该接的组合」，跟没做这一层一样；
   * 而必填会让它变成一次编译错误，在写完那一刻就暴露。
   *
   * 空数组 = 纯输入节点，不接受任何上游。它连输入点都不该渲染 ——
   * 画一个能拖线过来却永远连不上的点，是在邀请用户犯错。
   */
  accepts: ProducedKind[];
  /**
   * 这个节点能产出什么。**声明成函数**是因为它可能是动态的：
   * 上传素材节点同一种类型，既可能产出图片也可能产出视频，
   * 得看这条素材实际是什么。
   *
   * 不声明 = 不产出任何东西（纯文本输入节点也声明 "text"，
   * 因为它的文字确实会被下游当输入用）。
   */
  producedKind?: (data: Record<string, unknown>) => ProducedKind | null;
  /**
   * 产物是否从节点参数（data）里取，而不是运行时的 outputAssetId。
   *
   * 上传素材属于这种：素材是它**自带的输入**，不是「跑出来的产物」。
   * 存在 data 里才能跟着画布一起防抖落库 —— 如果写 outputAssetId，
   * 保存接口为了不覆盖运行时状态是不碰那一列的，刷新后素材就消失了。
   */
  assetInData?: true;
  /**
   * 只能通过别的入口创建，不从画布左上角的「+ 节点」里直接点出来。
   *
   * 上传素材就是这种：它必须有真实的文件才有意义，
   * 允许手动新建的话会得到一张 assetId 为空的卡片 —— 点了没反应、也没内容，
   * 用户只会以为坏了。
   */
  uploadOnly?: true;
  /** 具名输入端口。不声明就是单个默认端口 */
  inputs?: NodeInputPort[];
  /**
   * 「生成方式」的推导规则：某个端口有没有接线，决定用哪种模式。
   *
   * 为什么不把这段 if 写在引擎里：
   * 引擎不该知道「首帧图」这个概念，那是视频节点的事。声明成规则后，
   * 将来加一个「多图参考」的节点也能复用同一套推导，引擎零改动。
   */
  modeRule?: {
    /** 存在 params 里的键名，比如 mode */
    param: string;
    /** 自动模式的值，比如 auto */
    auto: string;
    /** 看哪个端口。空字符串 = 默认端口（单输入节点） */
    port: string;
    /**
     * 上游必须产出**这种**才算「接上了」。不写则只判断「有没有接」。
     *
     * 判的是产物种类，不是节点类型。这一点很关键：
     * 视频节点只有一个输入端口，接进来的可能是图片、视频或一段文字。
     * 光看「有没有连线」会把「接了一段剧本」误判成图生视频，模型拿不到图，
     * 生成出来一个莫名其妙的东西，而报错发生在几十秒之后，极难归因。
     *
     * 早先这里写的是 sourceType（比对节点类型），但用户上传的图片
     * 是 media.asset 类型而不是 image.gen —— 类型比对会漏掉它们，
     * 明明接了图却被判成文生视频。所以改成比对产物种类。
     */
    sourceKind?: ProducedKind;
    /** 接了用什么值 */
    whenPresent: string;
    /** 没接用什么值 */
    whenAbsent: string;
  };
  /** 可对这个节点发起的临时动作 */
  actions?: NodeAction[];
  /**
   * 这个节点要调用哪种模型能力。null = 纯输入节点，不需要模型。
   *
   * 为什么这条要写进注册表，而不是在引擎里 `if (type === "text.prompt") continue`：
   * 执行引擎不该知道任何具体节点类型。它只问注册表「这个节点需要什么能力」，
   * 再拿能力去 Provider 注册表选模型。加一种新节点时，引擎零改动。
   */
  capability: "text" | "image" | "video" | null;
}

